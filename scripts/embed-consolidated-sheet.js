// Regenerates src/webparts/onboardingTracker/assets/consolidatedSheet.ts from the .xlsx next to it.
// The SPFx build does not bundle .xlsx files, so the workbook is embedded as base64.
// Run after replacing the workbook: node scripts/embed-consolidated-sheet.js
const fs = require('fs');
const path = require('path');

const assetsDir = path.join(__dirname, '..', 'src', 'webparts', 'onboardingTracker', 'assets');
const name = fs.readdirSync(assetsDir).filter(file => file.toLowerCase().endsWith('.xlsx'))[0];
if (!name) {
  throw new Error(`No .xlsx file found in ${assetsDir}`);
}

const base64 = fs.readFileSync(path.join(assetsDir, name)).toString('base64');
const lines = base64.match(/.{1,120}/g);
const output =
  `// Generated by scripts/embed-consolidated-sheet.js from "${name}" (base64), because the build does not bundle .xlsx files.\n` +
  `export const CONSOLIDATED_SHEET_FILE_NAME = '${name}';\n\n` +
  `export const CONSOLIDATED_SHEET_BASE64 =\n${lines.map(line => `  '${line}'`).join(' +\n')};\n`;

fs.writeFileSync(path.join(assetsDir, 'consolidatedSheet.ts'), output, 'utf8');
console.log(`Embedded ${name} (${lines.length} lines)`);
